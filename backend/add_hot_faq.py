for faq in HOT_FAQ:
    knowledge = FaqKnowledge(
        question=faq["question"],
        answer=faq["answer"],
        doc_source="热门问答",
        vector_sync=False
    )
    db.session.add(knowledge)

db.session.commit()
print(f"✅ 热门问答入库完成，共 {len(HOT_FAQ)} 条")

# 同步到向量库
print("正在同步到向量库...")
processor = get_knowledge_processor()
unsynced = FaqKnowledge.query.filter_by(vector_sync=False).all()
faq_docs = []
for faq in unsynced:
    faq_docs.append({
        "id": f"faq_{faq.id}",
        "text": f"问题：{faq.question}\n答案：{faq.answer}",
        "metadata": {"source": faq.doc_source, "type": "faq"}
    })

if faq_docs:
    processor.vector_db.add_documents(faq_docs)
    print(f"✅ 热门问答向量库同步完成，共 {len(faq_docs)} 条")

FaqKnowledge.query.filter_by(vector_sync=False).update({FaqKnowledge.vector_sync: True})
db.session.commit()

print(f"\n知识库总量：{processor.get_document_count()} 个文档块")